// Visual3D-style body skeleton, rendered on top of the hand mocap layer.
//
// Stick segments come from `<trial>/body_segments.csv` (generated by
// pipeline/09_visual3d/steps/s01_segment_body_csv.py): each segment is
// drawn between its `_a` and `_b` endpoint. Arm segments (upper_arm /
// forearm / hand) are intentionally NOT rendered here — shoulder, elbow,
// wrist and fingers come from the hand mocap layer (HAND_CONNECTIONS), which
// is anatomically denser. The CSV still contains those columns for
// downstream / external Visual3D consumers.
//
// Inter-segment links (no `_a/_b` suffix) glue the body together so the
// skeleton reads as one figure rather than 8 floating sticks:
//   - neck:    head_a → torso_b
//   - hips:    torso_a → each thigh_a
//   - shoulder anchors: torso_b → RSh / LSh (RSh/LSh come from the hand CSV)
